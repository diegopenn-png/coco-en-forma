export function getLanguage() {
  const specified = canonicalLanguage(new URLSearchParams(globalThis.location?.search).get('lang'));
  if (specified) return specified;
  try {
    return canonicalLanguage(globalThis.localStorage?.getItem(storageKey)) || 'es';
  } catch {
    return 'es';
  }
}

export function setLanguage(value) {
  const language = canonicalLanguage(value) || 'es';
  try {
    globalThis.localStorage?.setItem(storageKey, language);
  } catch {
    // The URL also retains the setting when browser storage is disabled.
  }
  if (globalThis.location && globalThis.history) {
    const url = new URL(globalThis.location.href);
    url.searchParams.set('lang', language);
    globalThis.history.replaceState(globalThis.history.state, '', url);
  }
  return language;
}
