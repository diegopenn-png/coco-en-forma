"""Compile original teaching cards; normative sources are provenance, not model training.
Strict parsing rejects incomplete questions. Output is reproducible and contains no pupil data.
"""
import hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
RELEASE='eterna-library-2026.09-v1'
SOURCES={'infantil':('BOE-A-2022-1654','Real Decreto 95/2022'),'primaria':('BOE-A-2022-3296','Real Decreto 157/2022'),'eso':('BOE-A-2022-4975','Real Decreto 217/2022'),'bachillerato':('BOE-A-2022-5521','Real Decreto 243/2022')}
def canon(x):return json.dumps(x,ensure_ascii=False,sort_keys=True,separators=(',',':'))
def sha(x):return hashlib.sha256((x if isinstance(x,str) else canon(x)).encode()).hexdigest()
lessons=[];seen=set()
for f in sorted((ROOT/'qa/library').glob('lessons-*.txt')):
 stage='infantil' if 'infantil' in f.name else 'primaria' if 'primaria' in f.name else 'eso' if 'eso-' in f.name else 'bachillerato'
 for n,line in enumerate(f.read_text().splitlines(),1):
  if not line.strip():continue
  cols=line.split('|');assert len(cols)==12,(f.name,n,'columns',len(cols))
  lid,title,subject,years,aliases,explanation,simple,example,questions,hint,misconception,more=cols
  assert re.fullmatch(r'[a-z]+-[a-z0-9-]+',lid) and lid not in seen,(f,n,lid);seen.add(lid)
  low,high=map(int,years.split('-'));assert 1<=low<=high<=6
  qs=[]
  for i,part in enumerate(questions.split('$')):
   # Exact, reviewed correction of the sole malformed draft question.
   if lid=='i-compare' and i==2 and part=='Para comparar sin contar podemos…~Mirar solo la separación~Emparejar objetos~B':
    part='Para comparar sin contar podemos…~Mirar solo la separación~Emparejar objetos~Cambiar todas las piezas~B'
   q=part.split('~');assert len(q)==5,(lid,i,'MCQ must contain three options',part)
   prompt,a,b,c,key=q;assert key in 'ABC' and len({a,b,c})==3 and all([prompt,a,b,c])
   qs.append({'prompt':prompt,'options':[a,b,c],'answer_index':'ABC'.index(key)})
  assert len(qs)==3 and all(15<len(t)<1600 for t in [explanation,simple,example,hint,misconception,more]),lid
  if lid=='i-living':
   simple='Las plantas y los animales son seres vivos. Necesitan condiciones adecuadas para vivir. Un coche se mueve, pero no está vivo.'
  if lid=='p-to-be':
   qs[2]['options'][0]='Is she happy.' # Make the wrong option unambiguously not an ordinary written question.
  lesson={'id':lid,'stage':stage,'subject':subject,'title':title,'min_year':low,'max_year':high,'aliases':sorted(set(aliases.split(';')+[title])), 'explanation':explanation,'simple':simple,'example':example,'questions':qs,'hint':hint,'misconception':misconception,'more':more,
  'provenance':{'kind':'original_eterna_teaching_card','curricular_source':'https://www.boe.es/buscar/act.php?id='+SOURCES[stage][0],'legal_reference':SOURCES[stage][1],'mapping_status':'stage_reference_not_exhaustive_standard_mapping','placement':'pedagogical_recommendation_not_statutory_course_assignment','review':'assistant_editorial_and_structural_review','human_teacher_reviewed':False,'official_endorsement':False,'version':'1.0'}}
  lessons.append(lesson)
assert len(lessons)==80,len(lessons)
protocols=json.loads((ROOT/'qa/library/protocols-v1.json').read_text())
assert len({p['id'] for p in protocols})==len(protocols)
data={'release_id':RELEASE,'schema_version':1,'language':'es','scope_note':'First bounded block. Not full Spanish curriculum, not offline speech. Unknown or complex inputs retain the existing tutor route.','lessons':lessons,'protocols':protocols}
raw=canon(data);folder=ROOT/'eterna-worker/src/library';folder.mkdir(exist_ok=True)
(folder/'content-v1.json').write_text(raw+'\n')
(folder/'content-v1.js').write_text('// Generated by qa/library/build_library.py. Public teaching content only.\n'+'globalThis.EternaLibraryContentV1='+raw+';\n')
manifest={'release_id':RELEASE,'bundle_sha256':sha(raw),'lesson_count':len(lessons),'question_count':sum(len(l['questions']) for l in lessons),'protocol_count':len(protocols),'stage_counts':{s:sum(l['stage']==s for l in lessons) for s in SOURCES},'complete_curriculum':False,'human_teacher_reviewed':False,'microphone_changed':False}
(ROOT/'qa/library/library-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(manifest,ensure_ascii=False))
